#!/usr/bin/env python3
"""Build the extension artifacts for Chromium and Firefox.

One source tree, two browser packages. The script concatenates the shared
modules with each context entry point into a single classic-script bundle per
runtime context (background, content script, popup), copies the popup assets,
and writes the browser-appropriate manifest into ``dist/<target>/`` (NFR-004).

Usage (from the repository root):
    python3 scripts/build-extension.py

Standard library only; no third-party dependencies. Exits non-zero on error.
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
DIST = ROOT / "dist"

# Shared modules, in dependency order, bundled into every context.
COMMON = [
    "shared/browser-api.js",
    "shared/messages.js",
    "shared/state.js",
]

TARGETS = {
    "chromium": {
        "manifest": "manifest.chromium.json",
        "background": COMMON + ["background/background.js"],
        "content": COMMON + ["shared/selection.js", "content/panel.js", "content/content.js"],
        "popup": COMMON + ["popup/popup.js"],
    },
    "firefox": {
        "manifest": "manifest.firefox.json",
        "background": COMMON + ["background/background.js"],
        "content": COMMON + ["shared/selection.js", "content/panel.js", "content/content.js"],
        "popup": COMMON + ["popup/popup.js"],
    },
}

BUNDLE_BANNER = (
    "/* Generated by scripts/build-extension.py. Do not edit; edit src/ instead. */\n"
)


def read(relative: str) -> str:
    return (SRC / relative).read_text(encoding="utf-8")


def bundle(module_paths: list[str]) -> str:
    parts = [BUNDLE_BANNER]
    for rel in module_paths:
        parts.append(f"/* ---- {rel} ---- */\n")
        parts.append(read(rel))
        parts.append("\n")
    return "".join(parts)


def build_target(name: str, spec: dict[str, object]) -> None:
    out = DIST / name
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    manifest = json.loads(read(str(spec["manifest"])))
    if manifest.get("manifest_version") != 3:
        raise SystemExit(f"{name}: manifest is not Manifest V3")
    permissions = manifest.get("permissions")
    if sorted(permissions or []) != sorted(["storage", "activeTab", "scripting"]):
        raise SystemExit(f"{name}: unexpected permission set: {permissions!r}")

    (out / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )

    for context in ("background", "content", "popup"):
        (out / f"{context}.js").write_text(
            bundle(spec[context]), encoding="utf-8"  # type: ignore[arg-type]
        )

    shutil.copyfile(SRC / "popup" / "popup.html", out / "popup.html")
    shutil.copyfile(SRC / "popup" / "popup.css", out / "popup.css")

    print(f"[build] {name}: manifest.json, background.js, content.js, popup.js, "
          f"popup.html, popup.css")


def main() -> int:
    if not SRC.is_dir():
        print(f"error: source directory not found: {SRC}", file=sys.stderr)
        return 1
    DIST.mkdir(exist_ok=True)
    for name, spec in TARGETS.items():
        try:
            build_target(name, spec)
        except FileNotFoundError as exc:
            print(f"error: missing source file: {exc.filename}", file=sys.stderr)
            return 1
    print(f"[build] done: {DIST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
